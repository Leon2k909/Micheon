#!/usr/bin/env node
/**
 * Turn the emoji in wordPictures.ts into real artwork.
 *
 * The first version of the word pictures drew emoji as text, in whatever the
 * operating system happened to have. On Windows that is Segoe UI Emoji, and
 * Leon's verdict on it was "these emojis look terrible. nothing like what i was
 * expecting from the git repos" — which is fair: the flat two-tone Windows
 * glyphs look nothing like the rounded illustrated set that made the idea
 * appealing in the first place.
 *
 * So the pictures are now Twemoji, drawn from the same hand, shipped as SVG
 * with the app. This copies out ONLY the ones the map actually uses — around
 * five hundred of the three and a half thousand available — and writes a
 * module mapping each emoji to its file. Nothing is fetched at runtime; the
 * app stays fully offline.
 *
 * Twemoji is CC-BY 4.0. The credits page carries the attribution, and
 * check-word-pictures fails the build if it stops doing so.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const SOURCE = path.join(root, "node_modules", "@twemoji", "svg");
const OUT_DIR = path.join(root, "public", "word-pictures");
const OUT_MODULE = path.join(root, "src", "lib", "wordPictureAssets.ts");

if (!fs.existsSync(SOURCE)) {
  console.error("@twemoji/svg is not installed — run npm install first");
  process.exit(1);
}

// Every emoji the map can return, read straight out of the source so the two
// can never drift apart.
const mapSource = fs.readFileSync(path.join(root, "src", "lib", "wordPictures.ts"), "utf8");
const emoji = new Set();
for (const match of mapSource.matchAll(/:\s*"([^"a-zA-Z0-9 ][^"]*)"/g)) {
  const value = match[1];
  if (value && !/^[\x00-\x7F]*$/.test(value)) emoji.add(value);
}

/**
 * Twemoji names its files by codepoint, joined with dashes, and drops the
 * U+FE0F variation selector that only tells a text renderer to use colour —
 * except in the handful of sequences where it is load-bearing. Try the exact
 * sequence first, then the trimmed one.
 */
const codePoints = (value, stripVariationSelector) => {
  const points = [...value]
    .map((c) => c.codePointAt(0))
    .filter((c) => !(stripVariationSelector && c === 0xfe0f));
  return points.map((c) => c.toString(16)).join("-");
};

const chosen = new Map();
const missing = [];
for (const value of emoji) {
  const candidates = [codePoints(value, false), codePoints(value, true)];
  const found = candidates.find((name) => fs.existsSync(path.join(SOURCE, `${name}.svg`)));
  if (found) chosen.set(value, found);
  else missing.push(value);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
let bytes = 0;
for (const name of new Set(chosen.values())) {
  const svg = fs.readFileSync(path.join(SOURCE, `${name}.svg`));
  fs.writeFileSync(path.join(OUT_DIR, `${name}.svg`), svg);
  bytes += svg.length;
}

const rows = [...chosen.entries()]
  .sort((a, b) => a[1].localeCompare(b[1]))
  .map(([value, name]) => `  ${JSON.stringify(value)}: ${JSON.stringify(name)},`)
  .join("\n");

fs.writeFileSync(OUT_MODULE, `/**
 * Generated by scripts/build-word-pictures.cjs — do not edit by hand.
 *
 * Maps each emoji the word-picture map can return to the Twemoji SVG shipped
 * for it. Artwork is Twemoji, CC-BY 4.0; see the credits page.
 */
export const WORD_PICTURE_FILES: Record<string, string> = {
${rows}
};

/** Where the artwork is served from, relative to the app root. */
export const WORD_PICTURE_DIR = "/word-pictures";

/** The file for an emoji, or null when we ship no artwork for it. */
export function wordPictureAsset(emoji: string | null | undefined): string | null {
  if (!emoji) return null;
  const file = WORD_PICTURE_FILES[emoji];
  return file ? \`\${WORD_PICTURE_DIR}/\${file}.svg\` : null;
}
`);

console.log(`word pictures: ${chosen.size} emoji -> ${new Set(chosen.values()).size} SVGs, ${(bytes / 1024).toFixed(0)} KB`);
if (missing.length) {
  console.log(`no Twemoji artwork for ${missing.length}: ${missing.join(" ")}`);
}
