/** Les thèmes du cours, dans l'ordre où il les enseigne. */
export function frChapters(): string[] {
  const seen: string[] = [];
  for (const lesson of vivreEnFranceCourse.lessons ?? []) {
    if (!seen.includes(lesson.section)) seen.push(lesson.section);
  }
  return seen;
}

/**
 * Les leçons proposées par le sélecteur, avec le nombre de questions de
 * chacune.
 *
 * Tiré du cours lui-même : le titre et le thème viennent de la leçon, pas
 * d'un second répertoire qu'il faudrait tenir à jour à la main.
 */
export function frCategories(): { id: string; title: string; chapter: string; count: number }[] {
  const lessons = vivreEnFranceCourse.lessons ?? [];
  return lessons.map((lesson) => ({
    id: lesson.id,
    title: lesson.title,
    chapter: lesson.section,
    count: FR_QUESTIONS.filter((question) => question.lesson === lesson.id).length,
  }));
}

export function frQuestionsForLesson(lessonId: string): CountryQuestion[] {
  return FR_QUESTIONS.filter((question) => question.lesson === lessonId);
}

export function frQuestionsForChapter(chapter: string): CountryQuestion[] {
  const lessonIds = new Set(
    (vivreEnFranceCourse.lessons ?? []).filter((lesson) => lesson.section === chapter).map((lesson) => lesson.id)
  );
  return FR_QUESTIONS.filter((question) => lessonIds.has(question.lesson));
}

export function frQuestionById(id: string): CountryQuestion | undefined {
  return FR_QUESTIONS.find((question) => question.id === id);
}

export function frLessonTitle(lessonId: string): string {
  return (vivreEnFranceCourse.lessons ?? []).find((lesson) => lesson.id === lessonId)?.title ?? lessonId;
}

