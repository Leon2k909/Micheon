/**
 * Modern Greek translations keyed by the German catalogue text.
 *
 * Greek is the second course written in an alphabet of its own, after Russian,
 * and the first with nothing to switch it to: the cards are Greek and are shown
 * in Greek, because that is what a learner has to read on every sign in
 * Athens. What the alphabet makes hard is TYPING, and that is answered where
 * answers are graded — see greekTextMatch.ts, which takes a word typed in
 * Latin letters as a slip, and the lesson's Greek row, which is a keyboard.
 *
 * THE VARIETY is Standard Modern Greek as it is spoken in Greece today, in the
 * monotonic spelling: one tonos on every word of two or more syllables, the
 * diaeresis where two vowels are read apart, ς at the end of a word and σ
 * everywhere else. A question ends in ; — the Greek question mark is the
 * plain semicolon — and quotations sit in « ».
 *
 * THE STANDARD is what a Greek speaker would actually say in that situation,
 * at the register the German uses. A German sentence rebuilt word for word
 * fails even when every word is right, because the learner cannot tell and
 * will repeat it. So Gute Besserung is Περαστικά, Prost is Γεια μας,
 * Gesundheit after a sneeze is Γείτσες, and nur Bahnhof verstehen is a
 * sentence about Chinese.
 *
 * NOUNS CARRY THEIR ARTICLE — ο, η, το — because Greek gender is not
 * guessable from the German, and a bare noun drops half of what there is to
 * learn. Verbs are given in the first person singular of the present, which
 * is the form a Greek dictionary lists; adjectives in the masculine.
 *
 * FORMAL ADDRESS follows the German: du is εσύ, Sie is the polite εσείς. When
 * the learner speaks about themself, a phrasing that is the same for a man and
 * a woman is preferred wherever Greek has one — Κουράστηκα rather than Είμαι
 * κουρασμένος — and the masculine is written only where it has none.
 *
 * GREEK THINGS. A card that is not about life in Germany carries Greek people
 * and places: Anna is Άννα, Herr Müller is ο κύριος Παπαδόπουλος, a ticket to
 * Hamburg is a ticket to Θεσσαλονίκη. A card that IS about life in Germany —
 * the Bürgeramt, the Pfand, the Deutschlandticket — keeps everything German,
 * which is how a Greek living in Germany talks about them. The German language
 * itself stays German everywhere: Ich lerne Deutsch is Μαθαίνω γερμανικά.
 *
 * ONE ANSWER PER SPELLING. The course teaches a sentence in the form people
 * say it (ich hab) and the exam form (ich habe), and the app looks a card up
 * by whichever it is showing, so each German spelling of one sentence is a key
 * here with the same Greek beside it. They were written once and copied, never
 * translated twice, so the two can never drift apart.
 *
 * WHERE TWO GERMAN CARDS MEET ONE GREEK LINE they are left to collide and the
 * course keeps one card carrying both meanings, as the Portuguese table does.
 */
