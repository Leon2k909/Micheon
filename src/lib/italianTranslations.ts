/**
 * Italian, the fifth language taught from a table rather than a column.
 *
 * Same layer and same reasoning as spanishTranslations.ts: keyed on the German
 * text, so nothing in the packs is edited and no existing entry can break by
 * being touched. A card is only taught in Italian if it is in here, which
 * makes this file the syllabus rather than a decoration.
 *
 * WHICH ITALIAN. Standard Italian, the one taught and written across the
 * country rather than any single region's. That is a decision about grammar
 * as much as vocabulary:
 *   - the passato prossimo for the spoken past, as the north and centre use
 *     it: "Ieri sono andato dal medico", not the passato remoto.
 *   - tu, voi and Lei, mapped from the German below rather than chosen freely.
 *   - no regional lexis where the standard has a word: "anguria" and "cocomero"
 *     are both real, and the table keeps one of them everywhere.
 *
 * FORMS OF ADDRESS FOLLOW THE GERMAN. du -> tu, ihr -> voi, Sie -> Lei for one
 * person and voi for several. A German sentence on Sie must not quietly become
 * tu: the pair is what the learner is being taught, and getting it wrong
 * teaches them to be rude in an office.
 *
 * SPANISH IS BESIDE THIS FILE, AND IS NOT THE SOURCE. Every key here already
 * has a Spanish reading, and the two languages are close enough that the
 * Spanish is a useful check on register and idiom. It is a check and nothing
 * more. Translating from it rather than from the German is how burro (butter,
 * not a donkey), salire (to go up, not to leave) and guardare (to look, not to
 * keep) get written the Spanish way and are wrong in Italian while looking
 * entirely plausible.
 *
 * THE STANDARD. Spoken Italian, at the register the German uses. Set phrases
 * become set phrases, not word-for-word renderings:
 *   - Ubung macht den Meister -> La pratica rende perfetti.
 *   - Ich versteh nur Bahnhof -> Per me e arabo. (the idiom, not the station)
 *   - Daumen druecken -> incrociare le dita.
 * Italian drops the subject pronoun in speech - "Vado a casa", not "Io vado a
 * casa" - except where the German is contrastive and the Italian needs it too.
 *
 * NOUNS CARRY THEIR ARTICLE, keyed on the bare German noun with the Italian
 * article inside the value: "Abfluss" -> "lo scarico". The article is half of
 * what has to be learned about an Italian noun, and il/lo/la/l' is decided by
 * the sound that follows it, so a card without one teaches the noun and hides
 * the harder half.
 */
