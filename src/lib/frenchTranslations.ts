/**
 * French, kept out of the pack files.
 *
 * There were already 3,868 French translations in the course, written inline
 * as an `fr:` field beside the German — good, idiomatic ones, matched for
 * register rather than translated word for word. Two problems with them:
 * nothing displayed them (getCompanion() returns "none" and setCompanion is a
 * no-op), and they covered 18% of the catalogue.
 *
 * Adding the other 17,498 inline would mean editing megabytes of pack files
 * and reviewing a diff nobody could read. So new French lands here instead,
 * keyed by the German it translates. resolveFrench() merges the two sources,
 * and the inline ones stay exactly where they are.
 *
 * THE STANDARD. This is not a gloss table. It matches what the German course
 * does: the French is what a French speaker would actually say in that
 * situation, at the same register.
 *   - Übung macht den Meister → C'est en forgeant qu'on devient forgeron,
 *     not "la pratique rend parfait".
 *   - Verarschst du mich? → Tu te fous de moi ? — rude for rude.
 *   - Spoken French drops "ne": T'aurais pas une perceuse, par hasard ?
 *   - French spacing is real punctuation: a space before ! ? : and ;.
 * A literal translation that no French person would say is worse than no
 * translation, because the learner cannot tell the difference.
 */

