const essentialRank = new Map<string, number>(
  CONVERSATION_ESSENTIAL_PACKS.map((key, index) => [key, index])
);
const everydayRank = new Map<string, number>(
  EVERYDAY_CONVERSATION_PACKS.map((key, index) => [key, index])
);
const curriculumRank = new Map<string, number>(
  CURRICULUM_ORDER.map((key, index) => [key, index])
);

const dailyRank = new Map<string, number>(DAILY_LIFE_PACKS.map((key, index) => [key, index]));
const occasionalRank = new Map<string, number>(OCCASIONAL_PACKS.map((key, index) => [key, index]));
const lifeEventRank = new Map<string, number>(LIFE_EVENT_PACKS.map((key, index) => [key, index]));

function fallbackRank(partKey: string) {
  const known = curriculumRank.get(partKey);
  if (known != null) return known;
  const tatoeba = /^tatoeba-(a1|a2|b1|b2)-(\d+)$/i.exec(partKey);
  if (tatoeba) {
    const levelRank = ["a1", "a2", "b1", "b2"].indexOf(tatoeba[1].toLowerCase());
    return Math.max(0, levelRank) * 1_000 + Number(tatoeba[2] || 0);
  }
  return CURRICULUM_ORDER.length + 5_000;
}

/**
 * Honest, learner-facing usefulness category for an item.
 *
 * "Most common" in the tracker uses this category first, then the authored
 * pack order, then sentence-level frequency. It never promotes a niche corpus
 * sentence merely because its individual words happen to be frequent.
 */
export function conversationPriorityInfo(partKeyValue: string | undefined): ConversationPriorityInfo {
  const partKey = String(partKeyValue ?? "");

  if (partKey.startsWith("mine-")) {
    return {
      key: "personal",
      label: "Your material",
      hint: "Content you added yourself, kept near the front because it matters to you.",
      band: 1,
      packRank: fallbackRank(partKey),
    };
  }

  if (partKey.startsWith("tatoeba")) {
    return {
      key: "extra",
      label: "Extra practice",
      hint: "A broader real-sentence library for later practice, not an early conversation essential.",
      band: 7,
      packRank: fallbackRank(partKey),
    };
  }

  const essential = essentialRank.get(partKey);
  if (essential != null) {
    return {
      key: "essential",
      label: "Conversation essential",
      hint: "One of the first phrases to learn for starting, repairing or continuing a normal conversation.",
      band: 0,
      packRank: essential,
    };
  }

  const everyday = everydayRank.get(partKey);
  if (everyday != null) {
    return {
      key: "everyday",
      label: "Everyday conversation",
      hint: "Common next-step language for ordinary plans, people, places and daily needs.",
      band: 2,
      packRank: everyday,
    };
  }

  const meta = packMeta(partKey);
  if (meta.tier === 3) {
    return {
      key: "specialist",
      label: "Specialist / casual",
      hint: "Useful in a narrower, regional, technical or very casual context.",
      band: 6,
      packRank: fallbackRank(partKey),
    };
  }

  // The three bands below replace what used to be one "situational" bucket
  // holding 309 of 373 packs — so wide that past the essentials it sorted
  // nothing, and order fell to word frequency alone.
  const daily = dailyRank.get(partKey);
  if (daily != null) {
    return {
      key: "daily",
      label: "Daily life",
      hint: "Comes up most weeks: getting around, eating, working, feeling rough, talking to people.",
      band: 3,
      packRank: daily,
    };
  }

  const occasional = occasionalRank.get(partKey);
  if (occasional != null) {
    return {
      key: "occasional",
      label: "Now and then",
      hint: "Comes up sometimes — travel, appointments, hobbies, sport, screens, paperwork.",
      band: 4,
      packRank: occasional,
    };
  }

  const lifeEvent = lifeEventRank.get(partKey);
  if (lifeEvent != null) {
    return {
      key: "life-event",
      label: "Life events & big topics",
      hint: "Weddings, loss, politics, money worries and other things you meet rarely but need real words for.",
      band: 5,
      packRank: lifeEvent,
    };
  }

  return {
    key: "situational",
    label: "Situational",
    hint: "Useful when this situation comes up, after the main conversation essentials.",
    band: 4,
    packRank: fallbackRank(partKey) + (meta.tier === 2 ? 1_000 : 0),
  };
}

/**
 * Stable ascending score used by lessons, the tracker and pet recall.
 *
 * Category bands stay hard boundaries — essentials always come before
 * everyday material, and both before situational packs. INSIDE a band,
 * how common the sentence actually is drives the order: the guided flow
 * promises "what people say most, first", and authored pack order used to
 * override that (packRank * 10,000 dwarfed commonality's 0-5,000 range), so
 * reaching a niche pack pushed lines like "Ich war ein totaler Streber" ahead
 * of thousands of more common unseen phrases. Now an author's lessonPriority
 * can still deliberately promote or demote an item, phrases still edge out
 * vocabulary examples at equal commonality, and pack order is only the final
 * tie-break for lesson coherence.
 */
export function conversationPriorityScore(input: ConversationPriorityInput): number {
  const info = conversationPriorityInfo(input.partKey);
  const kindOffset = input.kind === "vocab" ? 60_000 : input.kind === "dialogue" ? 30_000 : 0;
  // One authored step outweighs a 1,500-point commonality gap — the same
  // relative strength it had before commonality was scaled up, so an editor's
  // deliberate promotion or demotion still decides the order inside a pack.
  const authored = Number.isFinite(input.lessonPriority)
    ? Math.max(-2, Math.min(2, Number(input.lessonPriority))) * 1_500_000
    : 0;
  const commonality = Number.isFinite(input.commonality)
    ? Math.max(0, Math.min(5_000, Number(input.commonality)))
    : 5_000;

  // Within-band total stays below the 10,000,000 band gap:
  // 5,000,000 + 3,000,000 + 60,000 + packRank < 10,000,000.
  return info.band * 10_000_000
    + commonality * 1_000
    + authored
    + kindOffset
    + info.packRank;
}

/**
 * The packs a Fast track sitting is allowed to draw from.
 *
 * Continue learning walks the whole curriculum in order, which is right for
 * somebody working through a course and wrong for somebody who wants to hold
 * a conversation this month. The course teaches the rooms of a house, the
 * things on a desk, the parts of a car — all of it worth knowing, none of it
 * what you reach for first when you are talking to a person.
 *
 * So this is the two conversational bands and nothing else, in the order they
 * were already authored in: opening a conversation, repairing it, reacting,
 * making plans, and then the topics a normal exchange actually turns to —
 * family, food, money, health, directions, the weather. What it leaves out is
 * as deliberate as what it keeps: no rooms, no furniture, no stationery.
 *
 * Written as the two existing lists joined rather than a third list copied
 * out of them, so a pack promoted into the essentials tomorrow is in the fast
 * track tomorrow and nobody has to remember this file exists.
 */
export const FAST_TRACK_PACKS: readonly string[] = [
  ...CONVERSATION_ESSENTIAL_PACKS,
  ...EVERYDAY_CONVERSATION_PACKS,
];

/**
 * Where a Fast track sitting picks up.
 *
 * The first conversational pack that still has something to teach, in the
 * authored order — so it continues rather than restarting, the same promise
 * Continue learning makes, over a much smaller course.
 *
 * `hasFresh` is passed in rather than computed here because deciding whether
 * a pack has fresh content means building its session, which needs the review
 * state, the learner and half the lesson engine. This file knows which packs
 * are conversational; it should not also have to know how a sitting is built.
 *
 * When every conversational pack is finished it returns the first one that
 * exists instead of null: the button is on screen and pressing it has to
 * teach something. Reviews inside that pack are what a finished course has
 * left to offer, and that is the same answer Continue learning gives.
 */
export function nextFastTrackPart(
  available: Record<string, unknown>,
  hasFresh: (packId: string) => boolean
): string | null {
  const present = FAST_TRACK_PACKS.filter((packId) => Boolean(available[packId]));
  return present.find((packId) => hasFresh(packId)) ?? present[0] ?? null;
}
