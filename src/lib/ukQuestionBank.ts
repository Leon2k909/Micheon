/**
 * The Life in the UK practice bank.
 *
 * Separate from the quizzes embedded in the lessons on purpose. Those exist to
 * close a lesson while the material is still on screen; these exist to be drawn
 * from repeatedly, in any order, long after the lesson was read. Mixing the two
 * would mean either a lesson that never ends or a practice pool of 23 questions.
 *
 * Every question carries the id of the lesson that teaches it, so "learn the
 * topic, then answer questions on that topic" is one filter rather than a
 * parallel taxonomy someone has to maintain by hand. The chapter comes from the
 * lesson, so filtering by broad area (history, government) and by narrow topic
 * (the Tudors, devolution) are the same mechanism.
 *
 * Difficulty is authored, not derived. Easy means the fact is stated plainly in
 * the lesson; medium means it needs recall of a specific name, date or number;
 * hard means it needs two facts held together, or it targets a trap the real
 * test is known to set — 55 BC against AD 43, 1807 against 1833, 1918 against
 * 1928.
 *
 * Nothing here is copied from the Home Office handbook or any commercial
 * question bank. The facts are public; the wording is ours.
 */

