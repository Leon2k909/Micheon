// ── Category model ────────────────────────────────────────────────────────
// Derived from the course rather than declared twice. A lesson added there
// becomes a filterable category here for free, and check-uk-questions fails if
// a question ever names a lesson that does not exist.

export type UkCategory = {
  /** The lesson id — also the value stored in UkQuestion.lesson. */
  id: string;
  title: string;
  /** One of the five official syllabus chapters. */
  chapter: string;
  count: number;
};

export function ukCategories(): UkCategory[] {
  const lessons = lifeInTheUkCourse.lessons ?? [];
  return lessons.map((lesson) => ({
    id: lesson.id,
    title: lesson.title,
    chapter: lesson.section,
    count: UK_QUESTIONS.filter((question) => question.lesson === lesson.id).length,
  }));
}

/** The five official chapters, in the order the course teaches them. */
export function ukChapters(): string[] {
  const seen: string[] = [];
  for (const lesson of lifeInTheUkCourse.lessons ?? []) {
    if (!seen.includes(lesson.section)) seen.push(lesson.section);
  }
  return seen;
}

export function ukQuestionsForLesson(lessonId: string): UkQuestion[] {
  return UK_QUESTIONS.filter((question) => question.lesson === lessonId);
}

export function ukQuestionsForChapter(chapter: string): UkQuestion[] {
  const lessonIds = new Set(
    (lifeInTheUkCourse.lessons ?? []).filter((lesson) => lesson.section === chapter).map((lesson) => lesson.id)
  );
  return UK_QUESTIONS.filter((question) => lessonIds.has(question.lesson));
}

export function ukQuestionById(id: string): UkQuestion | undefined {
  return UK_QUESTIONS.find((question) => question.id === id);
}

export function ukLessonTitle(lessonId: string): string {
  return (lifeInTheUkCourse.lessons ?? []).find((lesson) => lesson.id === lessonId)?.title ?? lessonId;
}
